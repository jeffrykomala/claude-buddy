// Generates the Shiba Inu sprite sheet and character.json used by the app:
//
//   node scripts/generate-shiba.mjs            -> public/characters/shiba/
//                                                 + src-tauri/icons/tray.png
//   node scripts/generate-shiba.mjs --preview <file.png>
//                                              -> also writes a 4x preview
//
// The art is drawn in code (scripts/shiba/), so it is original to this
// project and can be tweaked and regenerated at will.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { encodePng, sheetToRgba, upscale } from "./shiba/canvas.mjs";
import { FRAME_SIZE, buildPoses } from "./shiba/dog.mjs";

const OUTPUT_DIR = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "public",
  "characters",
  "shiba",
);
const TRAY_ICON_PATH = resolve(OUTPUT_DIR, "..", "..", "..", "src-tauri", "icons", "tray.png");
/** Displayed size / frame size: 32px art fills the 128pt pet window. */
const SCALE = 4;
const PREVIEW_SCALE = 4;

// Menu bar icon: the standing Shiba's head as a macOS "template" image, where
// only the alpha channel matters (the system tints it for light/dark bars).
const TRAY_CROP = { x: 0, y: 2, size: 18 };
const TRAY_SCALE = 2;
/** Opaque coat and outline, a lighter cream, and holes for eyes and nose. */
const TRAY_ALPHA = { O: 255, C: 255, S: 255, W: 120 };

function buildTrayIcon(standFrame) {
  const size = TRAY_CROP.size * TRAY_SCALE;
  const rgba = Buffer.alloc(size * size * 4);
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const key =
        standFrame[TRAY_CROP.y + Math.floor(y / TRAY_SCALE)][
          TRAY_CROP.x + Math.floor(x / TRAY_SCALE)
        ];
      rgba[(y * size + x) * 4 + 3] = key === null ? 0 : (TRAY_ALPHA[key] ?? 0);
    }
  }
  return encodePng(size, size, rgba);
}

/** Poses the Shiba has no drawing for borrow one it does have. */
const ALIASES = {
  listen: "stand",
  ask: "think",
  catch: "happy",
  read: "think",
  write: "think",
  browse: "think",
};

function buildCharacterJson(poses) {
  const sheetPoses = Object.fromEntries(
    poses.map((pose, row) => [
      pose.name,
      { row, frames: pose.frames.length, fps: pose.fps, loop: pose.loop },
    ]),
  );
  return {
    format: "sheet",
    name: "Shiba Inu",
    license:
      "Original pixel art generated by scripts/generate-shiba.mjs; same license as this project",
    image: "sheet.png",
    frameWidth: FRAME_SIZE,
    frameHeight: FRAME_SIZE,
    scale: SCALE,
    poses: sheetPoses,
    aliases: ALIASES,
  };
}

function main() {
  const poses = buildPoses();
  const columns = Math.max(...poses.map((pose) => pose.frames.length));
  const sheet = sheetToRgba(
    poses.map((pose) => pose.frames),
    columns,
  );

  mkdirSync(OUTPUT_DIR, { recursive: true });
  writeFileSync(join(OUTPUT_DIR, "sheet.png"), encodePng(sheet.width, sheet.height, sheet.rgba));
  writeFileSync(
    join(OUTPUT_DIR, "character.json"),
    `${JSON.stringify(buildCharacterJson(poses), null, 2)}\n`,
  );
  writeFileSync(TRAY_ICON_PATH, buildTrayIcon(poses[0].frames[0]));
  process.stdout.write(`Wrote ${poses.length} poses to ${OUTPUT_DIR}\n`);
  process.stdout.write(`Wrote the menu bar icon to ${TRAY_ICON_PATH}\n`);

  const previewAt = process.argv.indexOf("--preview");
  if (previewAt !== -1 && process.argv[previewAt + 1]) {
    const big = upscale(sheet, PREVIEW_SCALE);
    writeFileSync(process.argv[previewAt + 1], encodePng(big.width, big.height, big.rgba));
  }
}

main();
